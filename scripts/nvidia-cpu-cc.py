#!/usr/bin/env python3
"""Derive experimental CPU CC custom runtimes from installed Kata configs.

Requires Python 3.11+. Reads the installed reference configs and writes a
Helm values overlay to stdout; it does not modify the host or deploy anything.
"""

import argparse
import hashlib
import json
from pathlib import Path
import shlex
import sys

try:
    import tomllib
except ImportError:
    sys.exit("nvidia-cpu-cc.py requires Python 3.11 or newer")


TEES = {
    "snp": "amd.feature.node.kubernetes.io/snp",
    "tdx": "intel.feature.node.kubernetes.io/tdx",
}
KEY_RESOURCES = {"snp": "sev-snp.amd.com/esids", "tdx": "tdx.intel.com/keys"}


def toml_string(value):
    if not isinstance(value, str):
        raise ValueError("extension fields must be strings")
    return json.dumps(value, ensure_ascii=True)


def derive(config_dir, tee):
    base = f"qemu-nvidia-gpu-{tee}-runtime-rs"
    name = f"qemu-nvidia-cpu-{tee}-runtime-rs"
    handler = f"kata-{name}"
    source = config_dir / f"configuration-{base}.toml"
    data = source.read_bytes()
    config = tomllib.loads(data.decode())
    qemu = config["hypervisor"]["qemu"]
    if qemu.get("confidential_guest") is not True:
        raise ValueError(f"{source}: confidential_guest must be enabled")
    if (qemu.get("sev_snp_guest") is True) != (tee == "snp"):
        raise ValueError(f"{source}: CPU TEE does not match --tee {tee}")
    extensions = qemu["guest_extension_images"]
    if not isinstance(extensions, list) or not all(
        isinstance(entry, dict) for entry in extensions
    ):
        raise ValueError(f"{source}: expected guest_extension_images array")
    names = [entry.get("name") for entry in extensions]
    if any(not isinstance(name, str) or not name for name in names):
        raise ValueError(f"{source}: every extension must have a name")
    if len(names) != len(set(names)) or names.count("gpu") != 1:
        raise ValueError(f"{source}: expected exactly one GPU extension")
    if names.count("coco") != 1:
        raise ValueError(f"{source}: expected exactly one CoCo extension")
    retained = [entry for entry in extensions if entry["name"] != "gpu"]
    for entry in retained:
        if not entry.get("path") or not Path(entry["path"]).is_absolute():
            raise ValueError(f"{source}: extension path must be absolute")
        if set(entry) - {"name", "path", "verity_params"}:
            raise ValueError(f"{source}: unsupported extension fields")
        for value in entry.values():
            toml_string(value)
    coco = next(entry for entry in retained if entry["name"] == "coco")
    if not coco.get("verity_params", "").strip():
        raise ValueError(f"{source}: CoCo integrity metadata is missing")

    # Kata merges arrays by replacement. Re-emit every retained entry verbatim,
    # including dm-verity metadata, rather than inventing paths or root hashes.
    lines = [
        "# Generated by KRAB from the installed reference configuration.",
        f"# Source SHA256: {hashlib.sha256(data).hexdigest()}",
        "[hypervisor.qemu]",
    ]
    # Common drop-ins use the GPU base's DCGM setting. Override kernel_params
    # for this custom handler so a GPU handler cannot enable DCGM here. Keep
    # the reference boot arguments, including the confidential guest settings.
    params = qemu["kernel_params"]
    if not isinstance(params, str):
        raise ValueError(f"{source}: kernel_params must be a string")
    if any(word.startswith("nvrc.dcgm=") for word in shlex.split(params)):
        raise ValueError(f"{source}: expected reference kernel_params without DCGM")
    lines.append(f"kernel_params = {toml_string(params)}")
    for entry in retained:
        lines.extend(["", "[[hypervisor.qemu.guest_extension_images]]"])
        lines.extend(f"{key} = {toml_string(value)}" for key, value in entry.items())
    manifest = f"""apiVersion: node.k8s.io/v1
kind: RuntimeClass
metadata:
  name: {handler}
  labels:
    app.kubernetes.io/managed-by: kata-deploy
handler: {handler}
overhead:
  podFixed:
    {KEY_RESOURCES[tee]}: "1"
scheduling:
  nodeSelector:
    kubernetes.io/arch: amd64
    katacontainers.io/kata-runtime: "true"
    {TEES[tee]}: "true"
"""
    runtime = {
        "baseConfig": base,
        "dropIn": "\n".join(lines) + "\n",
        "runtimeClass": manifest,
        "inheritBaseOverhead": True,
        "containerd": {"snapshotter": "nydus"},
        "crio": {"pullType": "guest-pull"},
    }
    # The base needs architecture metadata even when it has no enabled built-in
    # RuntimeClass. Omit enabled: preserve an existing GPU handler's selection.
    shim = {"supportedArches": ["amd64"]}
    return name, base, runtime, shim


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config-dir", type=Path,
        default=Path("/opt/kata/share/defaults/kata-containers/runtime-rs"),
        help="directory containing the installed reference TOML files",
    )
    parser.add_argument("--tee", choices=["snp", "tdx", "both"], required=True)
    args = parser.parse_args()
    runtimes = {}
    shims = {}
    try:
        for tee in TEES if args.tee == "both" else [args.tee]:
            name, base, runtime, shim = derive(args.config_dir, tee)
            runtimes[name] = runtime
            shims[base] = shim
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"Cannot derive NVIDIA CPU CC runtime: {error}\n")
    # JSON is also valid Helm values YAML. Nothing is written until all selected
    # configurations have been validated, so failures never emit partial values.
    print(json.dumps({"kata-deploy": {
        "customRuntimes": {"enabled": True, "runtimes": runtimes},
        "shims": shims,
    }}, indent=2))


if __name__ == "__main__":
    main()
