import { parse, stringify } from 'yaml'

// Keep CPU detection identical to the pinned Kata rule without depending on
// the Kata deployment component being installed.
export function generateTeeFeatureRules(kataTemplate: string) {
  const spec = kataTemplate.match(/^spec:\n([\s\S]*?)\n\{\{- end \}\}\s*$/m)?.[1]
  if (!spec) throw new Error('Unable to extract the pinned Kata CPU feature rules')
  const { rules } = parse(spec)
  if (!Array.isArray(rules) || rules.length === 0) {
    throw new Error('The pinned Kata CPU feature rules are empty')
  }
  return `{{- /* Generated by npm run generate from kata-node-feature-rule. */ -}}
{{- if and (not (index .Values "kata-deploy" "enabled")) (or (index .Values "node-feature-discovery" "enabled") (.Capabilities.APIVersions.Has "nfd.k8s-sigs.io/v1alpha1")) }}
apiVersion: nfd.k8s-sigs.io/v1alpha1
kind: NodeFeatureRule
metadata:
  name: {{ .Release.Name }}-{{ .Release.Namespace }}-tee-capabilities
  labels:
    app.kubernetes.io/managed-by: {{ .Release.Service }}
    app.kubernetes.io/instance: {{ .Release.Name }}
${stringify({ spec: { rules } })}{{- end }}
`
}
